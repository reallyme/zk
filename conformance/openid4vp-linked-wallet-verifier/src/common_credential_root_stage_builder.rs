//! Synthetic issuance inputs with a fresh, request-scoped presentation salt.

use std::{fs, path::Path};

use buffa::{DecodeOptions, MessageField};
use crypto_csprng::OsSecureRandom;
use reallyme_zk_api::{
    circuits::ZkCredentialHashAlgorithm,
    common_root::{
        derive_common_credential_root_presentation_material,
        ZkCommonCredentialRootJoinDerivationInputs, ZkCommonCredentialRootPersonaMode,
        ZkCommonCredentialRootPresentationJoins, ZkCommonCredentialRootProofSlot,
        ZkCommonCredentialRootRequestJoinContext, ZkCommonCredentialRootStageSaltOwner,
        ZkCommonCredentialRootSubjectPublicKey,
    },
    proofs::{ZkSessionBinding, ABSENT_TRANSACTION_DATA_HASH},
};
use reallyme_zk_proto::generated::proto::reallyme::zk::v1 as pb;
use reallyme_zk_proto_codec::operation::ZkSensitiveProviderRequest;
use zeroize::Zeroizing;

use crate::error::HarnessError;

type Bytes32Field = MessageField<pb::ZkInputBytes32, buffa::Inline<pb::ZkInputBytes32>>;

pub(crate) fn common_credential_root_stage_requests_for_verified(
    stage_request_root: &Path,
    binding: ZkSessionBinding,
) -> Result<Vec<ZkSensitiveProviderRequest>, HarnessError> {
    common_credential_root_stage_requests_for_verified_profile(
        stage_request_root,
        binding,
        ZkCredentialHashAlgorithm::Sha256,
        ZkCommonCredentialRootPersonaMode::PrivatePersona,
    )
}

pub(crate) fn common_credential_root_stage_requests_for_verified_profile(
    stage_request_root: &Path,
    binding: ZkSessionBinding,
    credential_hash_algorithm: ZkCredentialHashAlgorithm,
    persona_mode: ZkCommonCredentialRootPersonaMode,
) -> Result<Vec<ZkSensitiveProviderRequest>, HarnessError> {
    let request = ZkCommonCredentialRootRequestJoinContext {
        challenge: binding.nonce_hash,
        audience_hash: binding.audience_hash,
        transaction_data_hash: binding
            .transaction_data_hash
            .unwrap_or(ABSENT_TRANSACTION_DATA_HASH),
    };
    let mut requests = Vec::new();
    requests
        .try_reserve_exact(ZkCommonCredentialRootProofSlot::ALL.len())
        .map_err(|_| HarnessError::InvalidLength)?;
    for slot in ZkCommonCredentialRootProofSlot::ALL {
        let path = stage_request_root.join(format!(
            "{}-{}-{}.pb",
            common_credential_root_lane(credential_hash_algorithm)?,
            common_credential_root_mode(persona_mode)?,
            slot.index()
        ));
        requests.push(read_provider_request(&path)?);
    }

    let root = Zeroizing::new(attestation_root(stage(&requests[0])?)?);
    let attestation_id = Zeroizing::new(status_attestation_id(stage(&requests[1])?)?);
    let subjects = [
        lineage_subject(stage(&requests[2])?)?,
        lineage_subject(stage(&requests[3])?)?,
    ];
    let mut rng = OsSecureRandom;
    let material = derive_common_credential_root_presentation_material(
        &mut rng,
        ZkCommonCredentialRootJoinDerivationInputs {
            request,
            root: &root,
            attestation_id: &attestation_id,
            subject_public_keys: subjects,
        },
    )?;
    let joins = material.joins();
    let mut salt_owner = material.into_stage_salt_owner();

    // The session signature is generated by the synthetic holder fixture.
    // Reject a stale template before changing any stage inputs: a signature
    // from another request must never be treated as freshly authorized.
    require_session_request(stage(&requests[6])?, persona_mode, request)?;
    for (slot, owner) in ZkCommonCredentialRootProofSlot::ALL
        .iter()
        .copied()
        .zip(requests.iter_mut())
    {
        let stage = stage_mut(owner)?;
        set_expected_binding(stage, binding);
        set_stage_input(stage, slot, request, joins, &mut salt_owner)?;
    }
    salt_owner.finish()?;
    Ok(requests)
}

fn read_provider_request(path: &Path) -> Result<ZkSensitiveProviderRequest, HarnessError> {
    let bytes = Zeroizing::new(fs::read(path)?);
    let request = DecodeOptions::new()
        .decode_from_slice::<pb::ZkProviderOperationRequest>(bytes.as_slice())
        .map_err(|_| HarnessError::InvalidLength)?;
    Ok(ZkSensitiveProviderRequest::new(request))
}

fn stage(
    owner: &ZkSensitiveProviderRequest,
) -> Result<&pb::ZkCommonCredentialRootStageProveOperation, HarnessError> {
    match owner.request().operation.as_ref() {
        Some(pb::zk_provider_operation_request::Operation::ProveCommonCredentialRootStage(
            stage,
        )) => Ok(stage.as_ref()),
        _ => Err(HarnessError::MissingField),
    }
}

fn stage_mut(
    owner: &mut ZkSensitiveProviderRequest,
) -> Result<&mut pb::ZkCommonCredentialRootStageProveOperation, HarnessError> {
    match owner.request_mut().operation.as_mut() {
        Some(pb::zk_provider_operation_request::Operation::ProveCommonCredentialRootStage(
            stage,
        )) => Ok(stage.as_mut()),
        _ => Err(HarnessError::MissingField),
    }
}

fn bytes32(field: &Bytes32Field) -> Result<[u8; 32], HarnessError> {
    let value = field.as_option().ok_or(HarnessError::MissingField)?;
    value
        .value
        .as_slice()
        .try_into()
        .map_err(|_| HarnessError::InvalidLength)
}

fn replace32(field: &mut Bytes32Field, value: &[u8; 32]) -> Result<(), HarnessError> {
    let target = field.as_option_mut().ok_or(HarnessError::MissingField)?;
    let target: &mut [u8; 32] = target
        .value
        .as_mut_slice()
        .try_into()
        .map_err(|_| HarnessError::InvalidLength)?;
    target.copy_from_slice(value);
    Ok(())
}

fn attestation_root(
    stage: &pb::ZkCommonCredentialRootStageProveOperation,
) -> Result<[u8; 32], HarnessError> {
    match stage.input.as_ref() {
        Some(pb::zk_common_credential_root_stage_prove_operation::Input::RootAttestation(
            input,
        )) => bytes32(&input.root),
        _ => Err(HarnessError::MissingField),
    }
}

fn status_attestation_id(
    stage: &pb::ZkCommonCredentialRootStageProveOperation,
) -> Result<[u8; 32], HarnessError> {
    match stage.input.as_ref() {
        Some(pb::zk_common_credential_root_stage_prove_operation::Input::RootStatus(input)) => {
            bytes32(&input.attestation_id)
        }
        _ => Err(HarnessError::MissingField),
    }
}

fn lineage_subject(
    stage: &pb::ZkCommonCredentialRootStageProveOperation,
) -> Result<ZkCommonCredentialRootSubjectPublicKey, HarnessError> {
    match stage.input.as_ref() {
        Some(pb::zk_common_credential_root_stage_prove_operation::Input::Lineage(input)) => {
            let witness = input
                .witness
                .as_option()
                .ok_or(HarnessError::MissingField)?;
            let key = witness
                .subject_public_key
                .as_option()
                .ok_or(HarnessError::MissingField)?;
            Ok(ZkCommonCredentialRootSubjectPublicKey {
                x: bytes32(&key.x)?,
                y: bytes32(&key.y)?,
            })
        }
        _ => Err(HarnessError::MissingField),
    }
}

fn require_session_request(
    stage: &pb::ZkCommonCredentialRootStageProveOperation,
    persona_mode: ZkCommonCredentialRootPersonaMode,
    request: ZkCommonCredentialRootRequestJoinContext,
) -> Result<(), HarnessError> {
    use pb::zk_common_credential_root_stage_prove_operation::Input;

    let session = match (persona_mode, stage.input.as_ref()) {
        (
            ZkCommonCredentialRootPersonaMode::PrivatePersona,
            Some(Input::PrivatePersonaSession(input)),
        ) => input
            .session_context
            .as_option()
            .ok_or(HarnessError::MissingField)?,
        (
            ZkCommonCredentialRootPersonaMode::PublicPersona,
            Some(Input::PublicPersonaSession(input)),
        ) => input
            .session_context
            .as_option()
            .ok_or(HarnessError::MissingField)?,
        _ => return Err(HarnessError::MissingField),
    };
    if bytes32(&session.challenge)? != request.challenge
        || bytes32(&session.audience_hash)? != request.audience_hash
        || bytes32(&session.transaction_data_hash)? != request.transaction_data_hash
    {
        return Err(HarnessError::InvalidPresentationAccepted);
    }
    Ok(())
}

fn set_expected_binding(
    stage: &mut pb::ZkCommonCredentialRootStageProveOperation,
    binding: ZkSessionBinding,
) {
    let target = stage.expected_binding.get_or_insert_default();
    target.nonce_hash.clear();
    target.nonce_hash.extend_from_slice(&binding.nonce_hash);
    target.audience_hash.clear();
    target
        .audience_hash
        .extend_from_slice(&binding.audience_hash);
    target.transaction_data_hash.clear();
    if let Some(hash) = binding.transaction_data_hash {
        target.transaction_data_hash.extend_from_slice(&hash);
    }
}

fn set_presentation(
    context: &mut pb::ZkInputPresentationContext,
    request: ZkCommonCredentialRootRequestJoinContext,
) -> Result<(), HarnessError> {
    replace32(&mut context.challenge, &request.challenge)?;
    replace32(&mut context.audience_hash, &request.audience_hash)?;
    replace32(
        &mut context.transaction_data_hash,
        &request.transaction_data_hash,
    )
}

fn set_stage_input(
    stage: &mut pb::ZkCommonCredentialRootStageProveOperation,
    slot: ZkCommonCredentialRootProofSlot,
    request: ZkCommonCredentialRootRequestJoinContext,
    joins: ZkCommonCredentialRootPresentationJoins,
    salt_owner: &mut ZkCommonCredentialRootStageSaltOwner,
) -> Result<(), HarnessError> {
    use pb::zk_common_credential_root_stage_prove_operation::Input;

    match (slot, stage.input.as_mut()) {
        (ZkCommonCredentialRootProofSlot::RootAttestation, Some(Input::RootAttestation(input))) => {
            set_presentation(input.presentation.get_or_insert_default(), request)?;
            replace32(&mut input.root_join, &joins.root_join)?;
            replace32(&mut input.attestation_join, &joins.attestation_join)?;
            copy_stage_salt(
                salt_owner,
                ZkCommonCredentialRootProofSlot::RootAttestation,
                request,
                &mut input.join_salt,
            )?;
        }
        (ZkCommonCredentialRootProofSlot::RootStatus, Some(Input::RootStatus(input))) => {
            set_presentation(input.presentation.get_or_insert_default(), request)?;
            replace32(&mut input.root_join, &joins.root_join)?;
            replace32(&mut input.attestation_join, &joins.attestation_join)?;
            copy_stage_salt(
                salt_owner,
                ZkCommonCredentialRootProofSlot::RootStatus,
                request,
                &mut input.join_salt,
            )?;
        }
        (
            ZkCommonCredentialRootProofSlot::Lineage0 | ZkCommonCredentialRootProofSlot::Lineage1,
            Some(Input::Lineage(input)),
        ) => {
            set_presentation(input.presentation.get_or_insert_default(), request)?;
            replace32(&mut input.root_join, &joins.root_join)?;
            let subject_index = subject_join_index(slot)?;
            replace32(
                &mut input.slot.get_or_insert_default().subject_join,
                &joins.subject_joins[subject_index],
            )?;
            copy_stage_salt(salt_owner, slot, request, &mut input.join_salt)?;
        }
        (
            ZkCommonCredentialRootProofSlot::SelectedClaim0
            | ZkCommonCredentialRootProofSlot::SelectedClaim1,
            Some(Input::PrivatePersonaClaim(input)),
        ) => {
            let issuer = input.issuer_context.get_or_insert_default();
            replace32(&mut issuer.challenge, &request.challenge)?;
            replace32(&mut issuer.audience_hash, &request.audience_hash)?;
            replace32(
                &mut issuer.transaction_data_hash,
                &request.transaction_data_hash,
            )?;
            let subject_index = selected_claim_join_index(slot)?;
            replace32(&mut input.subject_join, &joins.subject_joins[subject_index])?;
            copy_stage_salt(salt_owner, slot, request, &mut input.join_salt)?;
        }
        (
            ZkCommonCredentialRootProofSlot::SelectedClaim0
            | ZkCommonCredentialRootProofSlot::SelectedClaim1,
            Some(Input::PublicPersonaClaim(input)),
        ) => {
            let issuer = input.issuer_context.get_or_insert_default();
            replace32(&mut issuer.challenge, &request.challenge)?;
            replace32(&mut issuer.audience_hash, &request.audience_hash)?;
            replace32(
                &mut issuer.transaction_data_hash,
                &request.transaction_data_hash,
            )?;
            let subject_index = selected_claim_join_index(slot)?;
            replace32(&mut input.subject_join, &joins.subject_joins[subject_index])?;
            copy_stage_salt(salt_owner, slot, request, &mut input.join_salt)?;
        }
        (ZkCommonCredentialRootProofSlot::Session, Some(Input::PrivatePersonaSession(input))) => {
            let session = input.session_context.get_or_insert_default();
            replace32(&mut session.challenge, &request.challenge)?;
            replace32(&mut session.audience_hash, &request.audience_hash)?;
            replace32(
                &mut session.transaction_data_hash,
                &request.transaction_data_hash,
            )?;
        }
        (ZkCommonCredentialRootProofSlot::Session, Some(Input::PublicPersonaSession(input))) => {
            let session = input.session_context.get_or_insert_default();
            replace32(&mut session.challenge, &request.challenge)?;
            replace32(&mut session.audience_hash, &request.audience_hash)?;
            replace32(
                &mut session.transaction_data_hash,
                &request.transaction_data_hash,
            )?;
        }
        (
            ZkCommonCredentialRootProofSlot::IssuerCredentialStatus0
            | ZkCommonCredentialRootProofSlot::IssuerCredentialStatus1,
            Some(Input::IssuerCredentialStatus(input)),
        ) => {
            set_presentation(input.presentation.get_or_insert_default(), request)?;
        }
        _ => return Err(HarnessError::MissingField),
    }
    Ok(())
}

fn common_credential_root_lane(
    credential_hash_algorithm: ZkCredentialHashAlgorithm,
) -> Result<&'static str, HarnessError> {
    match credential_hash_algorithm {
        ZkCredentialHashAlgorithm::Sha256 => Ok("sha256"),
        ZkCredentialHashAlgorithm::Poseidon2 => Ok("poseidon2"),
        _ => Err(HarnessError::InvalidPresentationAccepted),
    }
}

fn common_credential_root_mode(
    persona_mode: ZkCommonCredentialRootPersonaMode,
) -> Result<&'static str, HarnessError> {
    match persona_mode {
        ZkCommonCredentialRootPersonaMode::PrivatePersona => Ok("private"),
        ZkCommonCredentialRootPersonaMode::PublicPersona => Ok("public"),
    }
}

fn copy_stage_salt(
    salt_owner: &mut ZkCommonCredentialRootStageSaltOwner,
    slot: ZkCommonCredentialRootProofSlot,
    request: ZkCommonCredentialRootRequestJoinContext,
    field: &mut Bytes32Field,
) -> Result<(), HarnessError> {
    let mut salt = Zeroizing::new([0_u8; 32]);
    salt_owner.copy_for_stage_witness(slot, request, &mut salt)?;
    replace32(field, &salt)
}

fn subject_join_index(slot: ZkCommonCredentialRootProofSlot) -> Result<usize, HarnessError> {
    match slot {
        ZkCommonCredentialRootProofSlot::Lineage0 => Ok(0),
        ZkCommonCredentialRootProofSlot::Lineage1 => Ok(1),
        _ => Err(HarnessError::InvalidLength),
    }
}

fn selected_claim_join_index(slot: ZkCommonCredentialRootProofSlot) -> Result<usize, HarnessError> {
    match slot {
        ZkCommonCredentialRootProofSlot::SelectedClaim0 => Ok(0),
        ZkCommonCredentialRootProofSlot::SelectedClaim1 => Ok(1),
        _ => Err(HarnessError::InvalidLength),
    }
}
